#!/usr/bin/env bash
# Writes infra/docker/images.env with fresh random seeds, if it does not exist
# yet (ADR 0019). The file is gitignored and excluded from the image build
# context; nothing here prints a value. Delete the file to start over with new
# seeds (credentials issued under the old ones then stop verifying).
#
# The API keys (CUSTOS_OPERATOR_KEY, *_SERVICE_KEY) are added by up.sh, since
# they must be created in the database.
set -euo pipefail

ENV_FILE="${CUSTOS_IMAGES_ENV:-infra/docker/images.env}"

if [ -f "$ENV_FILE" ]; then
  echo "images: using existing $ENV_FILE"
  exit 0
fi

hex32() {
  od -An -tx1 -N32 /dev/urandom | tr -d ' \n'
}

umask 077
{
  echo "# Custos images stack secrets. Generated by infra/docker/images/env.sh."
  echo "# Local only: gitignored, never baked into an image. Do not commit or share."
  echo "IDENTITY_ISSUER_SEED=$(hex32)"
  echo "REVOCATION_SIGNING_SEED=$(hex32)"
  echo "AUDIT_SIGNING_SEED=$(hex32)"
  echo "VAULT_MASTER_KEY=$(hex32)"
} >"$ENV_FILE"
echo "images: wrote new seeds to $ENV_FILE"
